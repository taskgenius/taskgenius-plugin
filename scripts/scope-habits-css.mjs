import fs from 'node:fs';
import postcss from 'postcss';
import selectorParser from 'postcss-selector-parser';

const directory = 'src/integrations/habits/';
const root = postcss.parse(fs.readFileSync(directory + 'upstream.css', 'utf8'));
root.walkRules(rule => {
  let parent = rule.parent;
  while (parent) {
    if (parent.type === 'atrule' && /keyframes$/i.test(parent.name)) return;
    parent = parent.parent;
  }
  rule.selector = selectorParser(selectors => {
    selectors.each(selector => {
      const scope = selectorParser().astSync(':where(.tg-habits-surface, .tg-habits-surface *)').first.first.clone();
      // Scope the subject of the selector, before pseudo-elements.
      const pseudo = selector.nodes.find(node => node.type === 'pseudo' && node.value.startsWith('::'));
      if (pseudo) selector.insertBefore(pseudo, scope);
      else selector.append(scope);
    });
  }).processSync(rule.selector);
});
fs.writeFileSync(directory + 'scoped.css', '/* Generated by scripts/scope-habits-css.mjs; upstream MIT licensed. */\n' + root.toString());
